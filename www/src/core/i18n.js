export const DICTS = { fr, en };
export const LANGS = ['fr', 'en'];
let lang = 'fr';

export function detectLang() {
  const nav = (typeof navigator !== 'undefined' && (navigator.languages?.[0] || navigator.language)) || 'fr';
  return nav.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function setLang(l) {
  lang = LANGS.includes(l) ? l : 'fr';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

/** Translate a key, with {param} interpolation. Falls back to French. */
export function t(key, params) {
  let s = DICTS[lang][key] ?? fr[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
  return s;
}

/** Plural-aware translation: uses `${key}.one` / `${key}.other`. */
export function tn(key, n, params = {}) {
  const one = lang === 'fr' ? Math.abs(n) < 2 : Math.abs(n) === 1;
  return t(`${key}.${one ? 'one' : 'other'}`, { n, ...params });
}

/** Locale-aware number formatting (French uses a narrow no-break space). */
export function num(n) {
  try {
    return new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : 'en-GB').format(n);
  } catch {
    return String(n);
  }
}
